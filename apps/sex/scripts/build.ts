// Builds dist/sex. A Bun executable with the JavaScript bundled. `SEX_TARGET` picks the platform
// (bun-linux-x64, bun-darwin-arm64, ...), `SEX_LOCAL_BINARY` embeds a firecrawl-local build of a specific version
// (the release pipeline's job), otherwise the binary is looked up on PATH at runtime.
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dir, "..", "..", "..");
let entry = join(root, "apps", "sex", "src", "cli.ts");

const binary = process.env.SEX_LOCAL_BINARY;
if (binary) {
  const bytes = new Uint8Array(await Bun.file(binary).arrayBuffer());
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const version = process.env.SEX_LOCAL_VERSION ?? "dev";
  const generated = join(root, "apps", "sex", "src", "cli.embedded.gen.ts");
  await writeFile(
    generated,
    `// Generated by apps/sex/scripts/build.ts; not checked in.
import { registerEmbedded } from "@searxng-js/sex-local";
import file from ${JSON.stringify(binary)} with { type: "file" };
registerEmbedded(${JSON.stringify(version)}, ${JSON.stringify(sha256)}, file);
const { run } = await import("./cli.ts");
run();
`,
  );
  entry = generated;
}

const target = process.env.SEX_TARGET as Bun.Build.CompileTarget | undefined;
const outfile = join(root, "dist", "sex");
await mkdir(join(root, "dist"), { recursive: true });
const result = await Bun.build({
  entrypoints: [entry],
  compile: { outfile, ...(target ? { target } : {}) },
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const size = (await Bun.file(outfile).size) / 1024 / 1024;
console.log(
  `dist/sex  ${target ?? "host"}  ${size.toFixed(1)} MB${binary ? `  firecrawl-local embedded from ${binary}` : ""}`,
);
